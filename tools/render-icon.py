#!/usr/bin/env python3
"""Writes the adaptive launcher icon from the iOS app's Design/AppIcon.svg construction.

The five family figures on a 100-unit grid, the app's own symbol in the middle. The figures
reach 45 units from the centre, so the artwork is scaled to sit inside the adaptive icon's
66 dp safe circle. Run once after changing the symbol; the outputs are committed.

  tools/render-icon.py
"""
import math, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
RES = ROOT / "app/src/main/res"
FAMILY = ["#FABB05", "#29ABE2", "#FF3B30", "#FFCC00", "#34C759"]

# The app's symbol: SVG transform and stroked elements, copied from the iOS Design/AppIcon.svg.
SYMBOL = {
    "colour": "#0A6E9C",
    "translate": (22.903, 14.645), "scale": 2.5806, "inner": (10.5, 13.7, 0.75, -12, -12),
    "stroke": 2.33,
    "paths": ["M19,10v2a7,7 0 0,1 -14,0v-2", "M12,19v3"],
    "circles": [],
    "rects": [(9, 2, 6, 12, 3)],
}

def circle_path(cx, cy, r):
    return f"M{cx - r:.3f},{cy:.3f}a{r:.3f},{r:.3f} 0 1,0 {2 * r:.3f},0a{r:.3f},{r:.3f} 0 1,0 {-2 * r:.3f},0z"

def rect_path(x, y, w, h, rx):
    return (f"M{x + rx:.3f},{y:.3f}h{w - 2 * rx:.3f}a{rx:.3f},{rx:.3f} 0 0,1 {rx:.3f},{rx:.3f}v{h - 2 * rx:.3f}"
            f"a{rx:.3f},{rx:.3f} 0 0,1 {-rx:.3f},{rx:.3f}h{-(w - 2 * rx):.3f}a{rx:.3f},{rx:.3f} 0 0,1 {-rx:.3f},{-rx:.3f}"
            f"v{-(h - 2 * rx):.3f}a{rx:.3f},{rx:.3f} 0 0,1 {rx:.3f},{-rx:.3f}z")

def figures(mono):
    out = []
    for i, angle in enumerate([0, 72, 144, 216, 288]):
        colour = "#000000" if mono else FAMILY[i]
        d = circle_path(50, 10, 4.4) + circle_path(41.5, 11, 2.2) + circle_path(58.5, 11, 2.2)
        out.append(f'    <group android:rotation="{angle}" android:pivotX="50" android:pivotY="50">\n'
                   f'      <path android:fillColor="{colour}" android:pathData="{d}" />\n    </group>')
    return "\n".join(out)

def symbol(mono):
    s = SYMBOL
    colour = "#000000" if mono else s["colour"]
    tx, ty = s["translate"]
    parts = [*s["paths"], *[circle_path(*c) for c in s["circles"]], *[rect_path(*r) for r in s["rects"]]]
    inner_open, inner_close = "", ""
    if s["inner"]:
        ix, iy, isc, ox, oy = s["inner"]
        inner_open = (f'<group android:translateX="{ix}" android:translateY="{iy}" android:scaleX="{isc}" android:scaleY="{isc}">'
                      f'<group android:translateX="{ox}" android:translateY="{oy}">')
        inner_close = "</group></group>"
    paths = "\n".join(
        f'        <path android:strokeColor="{colour}" android:strokeWidth="{s["stroke"]}" android:strokeLineCap="round" '
        f'android:strokeLineJoin="round" android:pathData="{p}" />' for p in parts)
    fills = "\n".join(
        f'        <path android:fillColor="{colour}" android:pathData="{rect_path(*r)}" />' for r in s.get("filled", []))
    return (f'    <group android:translateX="{tx}" android:translateY="{ty}" android:scaleX="{s["scale"]}" android:scaleY="{s["scale"]}">\n'
            f'      {inner_open}\n{paths}\n{fills}\n      {inner_close}\n    </group>')

def foreground(mono):
    # 100 units → 73 dp, centred in the 108 dp canvas: radius 45 units ≈ 33 dp, the safe circle.
    scale = 0.73
    offset = (108 - 100 * scale) / 2
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/render-icon.py from the iOS app's Design/AppIcon.svg. Do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
  <group android:translateX="{offset:.2f}" android:translateY="{offset:.2f}" android:scaleX="{scale}" android:scaleY="{scale}">
{figures(mono)}
{symbol(mono)}
  </group>
</vector>
'''

(RES / "drawable").mkdir(parents=True, exist_ok=True)
(RES / "drawable/ic_launcher_foreground.xml").write_text(foreground(False))
(RES / "drawable/ic_launcher_monochrome.xml").write_text(foreground(True))
(RES / "mipmap-anydpi").mkdir(parents=True, exist_ok=True)
(RES / "mipmap-anydpi/ic_launcher.xml").write_text('''<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
''')
print("written", file=sys.stderr)
